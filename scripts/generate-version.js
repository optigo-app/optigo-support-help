/**
 * 📦 Auto-increment build version + generate version.json & version.js
 * Automatically writes to both public/ and build/ (if present).
 * Use --sync-only to synchronize without incrementing the version number.
 */

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../");
const packagePath = path.join(root, "package.json");
const publicDir = path.join(root, "public");
const buildDir = path.join(root, "build");

const isSyncOnly = process.argv.includes("--sync-only");

(async () => {
  try {
    const packageJson = JSON.parse(fs.readFileSync(packagePath, "utf8"));
    let newVersion = packageJson.version;

    if (!isSyncOnly) {
      // Increment patch version
      const [major, minor, patch] = packageJson.version.split(".").map(Number);
      newVersion = `${major}.${minor}.${patch + 1}`;
      packageJson.version = newVersion;
      fs.writeFileSync(packagePath, JSON.stringify(packageJson, null, 2));
      console.log(`📦 Incremented package.json → version ${newVersion}`);
    } else {
      console.log(`📦 Syncing current package.json version ${newVersion}`);
    }

    const versionData = {
      version: newVersion,
      buildTime: new Date().toISOString(),
    };
    const jsonContent = JSON.stringify(versionData, null, 2);
    const jsContent = `// Auto-generated by generate-version.js\nwindow.__APP_VERSION__ = "${newVersion}";\nwindow.__BUILD_TIME__ = "${versionData.buildTime}";\n`;

    // Write to public/
    fs.writeFileSync(path.join(publicDir, "version.json"), jsonContent, "utf8");
    fs.writeFileSync(path.join(publicDir, "version.js"), jsContent, "utf8");
    console.log("✅ public/version.json & public/version.js updated:", versionData);

    // Sync to build/ if it exists
    if (fs.existsSync(buildDir)) {
      fs.writeFileSync(path.join(buildDir, "version.json"), jsonContent, "utf8");
      fs.writeFileSync(path.join(buildDir, "version.js"), jsContent, "utf8");
      console.log("✅ build/version.json & build/version.js synchronized directly");
    }

    console.log("🎉 Version handling completed successfully!");
  } catch (err) {
    console.error("❌ Error during version update:", err.message);
    process.exit(1);
  }
})();
